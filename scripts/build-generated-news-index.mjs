import fs from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const inputDir = path.join(root, "data", "news-generated");
const outputFile = path.join(root, "data", "generatedNews.js");

async function readGeneratedNews() {
  let files = [];
  try {
    files = await fs.readdir(inputDir);
  } catch {
    return [];
  }

  const posts = [];
  for (const file of files.filter((entry) => entry.endsWith(".json")).sort()) {
    try {
      const post = JSON.parse(await fs.readFile(path.join(inputDir, file), "utf8"));
      if (post.status !== "published" || post.quality?.passed === false) continue;
      posts.push(post);
    } catch {
      continue;
    }
  }
  return posts;
}

const posts = await readGeneratedNews();
const content = [
  "// This file is generated by scripts/build-generated-news-index.mjs.",
  "// Do not edit manually; edit data/news-generated/*.json or rerun the news system.",
  `export const generatedNewsPosts = ${JSON.stringify(posts, null, 2)};`,
  ""
].join("\n");

await fs.writeFile(outputFile, content, "utf8");
console.log(`Generated data/generatedNews.js with ${posts.length} published news item(s).`);
